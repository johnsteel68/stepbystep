import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { deflateRawSync } from 'node:zlib';
import { GOOGLE_STENCIL_FONTS } from '../googleStencilFonts.ts';
import { prepareFont } from './prepare-tenada.mjs';

const root = new URL('../', import.meta.url);
const sourceRoot = new URL('../FontSources/google/', import.meta.url);
const headers = { 'User-Agent': 'STEPbySTEP-font-importer' };
async function download(url) {
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  return Buffer.from(await response.arrayBuffer());
}
// Pin the entire import to one official repository revision, so metadata,
// fonts, licenses and provenance all refer to exactly the same upstream state.
const revision = process.argv.includes('--offline') ? null : JSON.parse((await download('https://api.github.com/repos/google/fonts/commits/main')).toString()).sha;
const fonts = {}, provenance = [];
function pointSegmentDistance(p, a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1], square = dx * dx + dy * dy;
  const t = square ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / square)) : 0;
  return Math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy);
}
for (const item of GOOGLE_STENCIL_FONTS) {
  const directory = new URL(`${item.directory}/`, sourceRoot);
  await mkdir(directory, { recursive: true });
  const metadataPath = new URL('METADATA.pb', directory);
  const base = `https://raw.githubusercontent.com/google/fonts/${revision}/ofl/${item.directory}/`;
  if (revision) {
    const metadata = await download(`${base}METADATA.pb`);
    if (!metadata.toString().includes('license: "OFL"')) throw new Error(`Unsupported license: ${item.directory}`);
    await writeFile(metadataPath, metadata);
    const license = await download(`${base}OFL.txt`);
    if (!license.toString().includes('SIL OPEN FONT LICENSE')) throw new Error(`Missing OFL: ${item.directory}`);
    await writeFile(new URL('OFL.txt', directory), license);
  }
  const metadata = (await readFile(metadataPath)).toString();
  const block = [...metadata.matchAll(/fonts \{([\s\S]*?)\n\}/g)].find(match => match[1].includes(`weight: ${item.weight}`) && match[1].includes('style: "normal"'));
  const filename = block?.[1].match(/filename: "([^"]+)"/)?.[1];
  if (!filename || filename.includes('[')) throw new Error(`No supported static font: ${item.directory}`);
  const source = new URL(filename, directory);
  if (revision) await writeFile(source, await download(`${base}${encodeURIComponent(filename)}`));
  // Open each actual enclosed counter at its own centre. Fixed horizontal
  // bands can leave tiny slivers in rounded letters, so do not add them here.
  const glyphs = prepareFont(source);
  // This catches small detached strokes/dots as well as thin bounding boxes.
  // It is a conservative design screen, not an atelier-certified capability.
  let smallest = Infinity;
  for (const glyph of Object.values(glyphs)) for (const ring of glyph.contours) {
    const x = ring.map(p => p[0]), y = ring.map(p => p[1]);
    smallest = Math.min(smallest, Math.max(...x) - Math.min(...x), Math.max(...y) - Math.min(...y));
  }
  // Native stencil openings sometimes have finer bridges than 1/24 cap
  // height. Account for the shortest retained gap between cut components.
  for (const glyph of Object.values(glyphs)) for (let i = 0; i < glyph.contours.length; i++) {
    const ring = glyph.contours[i];
    for (const other of glyph.contours.slice(i + 1)) for (let a = 0; a < ring.length; a++) for (let b = 0; b < other.length; b++) {
      const p = ring[a], q = ring[(a + 1) % ring.length], r = other[b], s = other[(b + 1) % other.length];
      smallest = Math.min(smallest, pointSegmentDistance(p, r, s), pointSegmentDistance(q, r, s), pointSegmentDistance(r, p, q), pointSegmentDistance(s, p, q));
    }
  }
  const minimumFactor = Math.max(24, Math.ceil(1 / smallest * 1.01));
  if (!Number.isFinite(minimumFactor) || minimumFactor > 150) throw new Error(`Unsuitable tiny features: ${item.directory}`);
  fonts[item.id] = { minimumFactor, compressed: deflateRawSync(JSON.stringify(glyphs), { level: 9 }).toString('base64') };
  provenance.push({ id: item.id, filename, source: `https://github.com/google/fonts/tree/${revision ?? 'main'}/ofl/${item.directory}`, sha256: createHash('sha256').update(await readFile(source)).digest('hex'), license: 'SIL OFL 1.1', adaptation: 'Vector cutting contours with reinforced counter bridges; original font binary unmodified.' });
  console.log(`${item.label}: ${minimumFactor} × thickness`);
}
await writeFile(new URL('googleStencilGlyphs.ts', root), `// Generated by scripts/prepare-google-stencils.mjs. Do not hand-edit.\nexport const GOOGLE_STENCIL_DATA: Record<string, { minimumFactor: number; compressed: string }> = ${JSON.stringify(fonts)};\n`);
if (revision) await writeFile(new URL('PROVENANCE.json', sourceRoot), JSON.stringify({ repository: 'google/fonts', revision, fonts: provenance }, null, 2));
